def lattice2_add(basis, v):
    """Integer 2D lattice: maintain HNF-ish basis [(a,b),(0,c)]."""
    if v == (0, 0):
        return basis
    vecs = basis + [v]
    # reduce to HNF via gcd steps
    # collect all vectors, do integer row reduction
    a = [list(x) for x in vecs]
    # first column
    while True:
        nz = [r for r in a if r[0] != 0]
        if len(nz) <= 1:
            break
        nz.sort(key=lambda r: abs(r[0]))
        p = nz[0]
        for r in nz[1:]:
            q = r[0] // p[0]
            r[0] -= q * p[0]
            r[1] -= q * p[1]
        a = [r for r in a if r != [0, 0]]
    first = next((r for r in a if r[0] != 0), None)
    rest = [r for r in a if r[0] == 0 and r[1] != 0]
    g2 = 0
    for r in rest:
        g2 = math.gcd(g2, abs(r[1]))
    if first and g2:
        first[1] %= g2
    out = []
    if first:
        out.append(tuple(first))
    if g2:
        out.append((0, g2))
    return out


def in_lattice(basis, v):
    x, y = v
    b1 = next((b for b in basis if b[0] != 0), None)
    g2 = next((b[1] for b in basis if b[0] == 0), None)
    if b1 is None:
        if v == (0, 0):
            return True
        if g2 is None:
            return False
        return x == 0 and y % g2 == 0
    if x % b1[0] != 0:
        return False
    k = x // b1[0]
    ry = y - k * b1[1]
    if ry == 0:
        return True
    return g2 is not None and ry % g2 == 0


