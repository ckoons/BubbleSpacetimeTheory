def dot(a,b): return np.sum(a*b)
def trip(x,y,z): yb=np.conj(y); return dot(x,yb)*z+dot(z,yb)*x-dot(x,z)*yb
def D(a,b): return np.array([trip(a,b,np.eye(n)[k]) for k in range(n)]).T
