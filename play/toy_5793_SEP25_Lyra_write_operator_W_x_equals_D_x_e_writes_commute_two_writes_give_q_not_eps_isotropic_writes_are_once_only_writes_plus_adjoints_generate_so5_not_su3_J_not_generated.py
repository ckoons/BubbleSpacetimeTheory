W=[D(x,e) for x in V1]; Wd=[D(e,x) for x in V1]
print('W^dag = D(e,x)?', all(np.allclose(W[i].conj().T, Wd[i]) for i in range(3)))
print('[Wx,Wy]=0:', all(np.allclose(A@B-B@A,0) for A in W for B in W))
