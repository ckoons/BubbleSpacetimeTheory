    print(f'\n## Nipp rows parsed: {len(rows)}; d range {min(r["d"] for r in rows)}..{max(r["d"] for r in rows)}')
    # parse validation: genus masses
    from collections import defaultdict
    gsum = defaultdict(Fraction); gmass = {}
    for r in rows:
        gsum[(r['d'], r['g'])] += Fraction(1, r['G']); gmass[(r['d'], r['g'])] = r['mass']
    bad = [k for k in gsum if gsum[k] != gmass[k]]
    print(f'  genus-mass check: {len(gsum)-len(bad)}/{len(gsum)} genera have sum 1/G = m1/m2 (mismatches: {bad[:5]})')

    print('\n## Parts B+C: squarefree N — chamber mass vs Nipp mass identity (P1), per class (P2), |O| pin (P3)')
    print('  N | omega_odd | r*(N) | 2^w * sum_{adm} 1/|O| (Nipp) | P1 | classes: mine / Nipp adm / Nipp non-adm | P2 | P3(|O| mine=Nipp)')
    P1 = P2 = P3 = True; results = []
    for N in range(1, Nmax+1):
        fs = squarefree_factors(N)
        if fs is None: continue
        w = sum(1 for p in fs if p != 2)
        nipp = nipp_classes_of_gram_det(rows, N)
        for c in nipp: c['adm'] = admissible(c['G'], N)
        adm = [c for c in nipp if c['adm']]; nonadm = [c for c in nipp if not c['adm']]
        nipp_mass = 2**w * sum(Fraction(1, c['aut']) for c in adm)
        p1 = (rprim[N] == nipp_mass); P1 &= p1
        # my classes from x^perp
        grams = [gram_of_perp(x) for x, _, p in data[N] if p]
        for G in grams: assert det_int(G) == N
        cls = classify(grams)
        # per-class chamber mass
        p2 = True; p3 = True
        for c in cls:
            mass_c = sum(Fraction(1, data[N][[k for k,(x,_,p) in enumerate(data[N]) if p][m]][1]) for m in c['members'])
            c['chamber_mass'] = mass_c
            # match to a Nipp admissible class
            match = None
            for nc in nipp:
                cnt, _ = isometries(pair_reduce(c['rep']), pair_reduce(nc['G']), limit=1)
                if cnt: match = nc; break
            c['nipp'] = match
            if match is None or not match['adm']:
                p2 = False
            else:
                p3 &= (match['aut'] == c['aut'])
                p2 &= (mass_c == Fraction(2**w, c['aut']))
        # every admissible Nipp class must appear among mine
        if len(cls) != len(adm) or any(c['nipp'] is None for c in cls): p2 = False
        P2 &= p2; P3 &= p3
        print(f'  {N:3d} | {w} | {str(rprim[N]):>9} | {str(nipp_mass):>9} | {"HIT " if p1 else "MISS"} | {len(cls)} / {len(adm)} / {len(nonadm)} | {"HIT " if p2 else "MISS"} | {"HIT " if p3 else "MISS"}')
        results.append(dict(N=N, omega_odd=w, rstar=str(rprim[N]), nipp_mass=str(nipp_mass), P1=p1, P2=p2, P3=p3,
                            my_classes=[dict(rep=c['rep'], aut=c['aut'], chamber_mass=str(c['chamber_mass']), orbits=len(c['members']),
                                             nipp_aut=(c['nipp']['aut'] if c['nipp'] else None), nipp_parity=(c['nipp']['parity'] if c['nipp'] else None)) for c in cls],
                            nipp_nonadmissible=[dict(G=c['G'], aut=c['aut'], parity=c['parity']) for c in nonadm]))
    print(f'\nP1 mass identity (all squarefree N<={Nmax}): {"HIT" if P1 else "MISS"}')
    print(f'P2 per-class identity + admissible<->appears:  {"HIT" if P2 else "MISS"}')
    print(f'P3 |O(L)| mine = Nipp G on every matched class: {"HIT" if P3 else "MISS"}')
    print(f'P4 reproduction of K1862-A:                     {"HIT" if p4 else "MISS"}')
    out = dict(toy=5697, Nmax=Nmax, P1=P1, P2=P2, P3=P3, P4=p4, rstar_all={N: str(rstar[N]) for N in range(1, Nmax+1)},
               orbits_all={N: len(data[N]) for N in range(1, Nmax+1)}, results=results, seconds=round(time.time()-t0, 1))
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '.toy_5697_results.json'), 'w') as f:
        json.dump(out, f, indent=1)
    print(f'elapsed {time.time()-t0:.1f}s; results in play/.toy_5697_results.json')

