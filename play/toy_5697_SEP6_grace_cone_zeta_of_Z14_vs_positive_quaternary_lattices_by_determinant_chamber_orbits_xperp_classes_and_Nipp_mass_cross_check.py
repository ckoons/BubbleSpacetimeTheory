def int_kernel_basis(w):
    """Integer basis of {v in Z^m : w.v = 0} for an integer row vector w (not all zero)."""
    m = len(w)
    w = list(w)
    U = [[1 if i == j else 0 for j in range(m)] for i in range(m)]   # columns of U are basis vectors; w*U tracked in w
    def colop(j, i, q):   # column j -= q * column i
        for k in range(m): U[k][j] -= q*U[k][i]
        w[j] -= q*w[i]
    def swap(i, j):
        for k in range(m): U[k][i], U[k][j] = U[k][j], U[k][i]
        w[i], w[j] = w[j], w[i]
    # Euclid all entries into position 0
    while any(w[j] != 0 for j in range(1, m)):
        # move the smallest nonzero |w| to position 0
        j0 = min((j for j in range(m) if w[j] != 0), key=lambda j: abs(w[j]))
        if j0 != 0: swap(0, j0)
        for j in range(1, m):
            if w[j] != 0:
                q = w[j] // w[0]
                colop(j, 0, q)
    return [[U[k][j] for k in range(m)] for j in range(1, m)]   # list of basis vectors (rows here)

def gram_of_perp(x):
    """Positive-definite integer Gram matrix of x^perp (Lorentzian form negated), for x with Q(x) > 0."""
    w = [x[0]] + [-xi for xi in x[1:]]
    basis = int_kernel_basis(w)
    n = len(basis)
    G = [[-B(basis[i], basis[j]) for j in range(n)] for i in range(n)]
    return G

def det_int(M):
    M = [list(map(Fraction, row)) for row in M]; n = len(M); d = Fraction(1)
    for i in range(n):
        p = next((r for r in range(i, n) if M[r][i] != 0), None)
        if p is None: return 0
        if p != i: M[i], M[p] = M[p], M[i]; d = -d
        d *= M[i][i]
        for r in range(i+1, n):
            f = M[r][i] / M[i][i]
            for c in range(i, n): M[r][c] -= f*M[i][c]
    assert d.denominator == 1
    return int(d)

def pair_reduce(G):
    """Greedy pairwise reduction of a positive-definite Gram matrix (exact, integer)."""
    n = len(G); G = [row[:] for row in G]
    changed = True
    while changed:
        changed = False
        for i in range(n):
            for j in range(n):
                if i == j: continue
                q = round(G[i][j] / G[j][j])
                if q == 0: continue
                newii = G[i][i] - 2*q*G[i][j] + q*q*G[j][j]
                if newii < G[i][i]:
                    # b_i <- b_i - q b_j
                    for k in range(n):
                        if k != i: G[i][k] -= q*G[j][k]; G[k][i] = G[i][k]
                    G[i][i] = newii
                    changed = True
        # sort by diagonal
        order = sorted(range(n), key=lambda i: G[i][i])
        if order != list(range(n)):
            G = [[G[a][b] for b in order] for a in order]; changed = True
    return G

def short_vectors(G, C):
    """All integer v != 0 with v^T G v <= C (Fincke–Pohst with exact rational Cholesky, exact final check)."""
    n = len(G)
    # q_ij as Fractions: Q(v) = sum_i q_ii (v_i + sum_{j>i} q_ij v_j)^2
    q = [[Fraction(0)]*n for _ in range(n)]
    A = [[Fraction(G[i][j]) for j in range(n)] for i in range(n)]
    for i in range(n):
        q[i][i] = A[i][i]
        for j in range(i+1, n):
            q[i][j] = A[i][j] / A[i][i]
        for k in range(i+1, n):
            for l in range(k, n):
                A[k][l] -= q[i][k]*q[i][l]*A[i][i]; A[l][k] = A[k][l]
    out = []
    v = [0]*n
    def rec(i, T):
        # T = remaining budget (Fraction)
        c = -sum(q[i][j]*v[j] for j in range(i+1, n))
        rad = math.sqrt(float(T / q[i][i])) + 1e-9
        lo = math.ceil(float(c) - rad); hi = math.floor(float(c) + rad)
        for vi in range(lo, hi+1):
            v[i] = vi
            T2 = T - q[i][i]*(vi - c)**2
            if T2 < 0: continue
            if i == 0:
                vec = tuple(v)
                if any(vec):
                    val = sum(G[a][b]*vec[a]*vec[b] for a in range(n) for b in range(n))
                    if val <= C: out.append((val, vec))
            else:
                rec(i-1, T2)
        v[i] = 0
    rec(n-1, Fraction(C))
    return out

def theta_invariant(G, C):
    sv = short_vectors(G, C)
    cnt = {}
    for val, _ in sv: cnt[val] = cnt.get(val, 0) + 1
    return tuple(sorted(cnt.items()))

def isometries(G1, G2, limit=None):
    """All integer matrices V (columns v_i) with V^T G2 V = G1, i.e. isometries L1 -> L2; returns the count (and first found)."""
    n = len(G1)
    C = max(G1[i][i] for i in range(n))
    sv = short_vectors(G2, C)
    bynorm = {}
    for val, vec in sv: bynorm.setdefault(val, []).append(vec)
    cands = [bynorm.get(G1[i][i], []) for i in range(n)]
    def ip(u, w): return sum(G2[a][b]*u[a]*w[b] for a in range(n) for b in range(n))
    count = 0; first = None
    chosen = []
    def rec(i):
        nonlocal count, first
        if i == n:
            count += 1
            if first is None: first = [c[:] for c in chosen]
            return
        for vec in cands[i]:
            if all(ip(vec, chosen[j]) == G1[i][j] for j in range(i)):
                chosen.append(list(vec)); rec(i+1); chosen.pop()
                if limit and count >= limit: return
    rec(0)
    return count, first

def classify(grams, C_extra=0):
    """Group Gram matrices into isometry classes. Returns list of classes: dict(rep=G, members=[indices], aut=|O(L)|)."""
    classes = []
    inv_index = {}
    reduced = [pair_reduce(G) for G in grams]
    # one common theta bound for the whole batch: pairwise reduction is not canonical, so a per-Gram bound
    # would put isometric lattices in different invariant buckets (caught 10:12 on N = 21: 4 classes for 3)
    C_common = max((G[i][i] for G in reduced for i in range(len(G))), default=0) + C_extra
    for idx, G in enumerate(reduced):
        C = C_common
        inv = (det_int(G), theta_invariant(G, C))
        placed = False
        for ci in inv_index.get(inv, []):
            cnt, _ = isometries(G, classes[ci]['rep'], limit=1)
            if cnt > 0:
                classes[ci]['members'].append(idx); placed = True; break
        if not placed:
            aut, _ = isometries(G, G)
            classes.append({'rep': G, 'members': [idx], 'aut': aut})
            inv_index.setdefault(inv, []).append(len(classes)-1)
    return classes

