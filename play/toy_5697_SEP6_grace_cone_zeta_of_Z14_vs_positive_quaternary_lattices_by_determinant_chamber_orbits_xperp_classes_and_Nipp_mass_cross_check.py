def B(x, y):
    """Lorentzian bilinear form x0 y0 - sum xi yi."""
    return x[0]*y[0] - sum(a*b for a, b in zip(x[1:], y[1:]))

def vinberg_roots(n):
    """Simple roots of O+(Z^{1,n}), n>=2, signed so the chamber is {x : B(x,r) >= 0 for all r}.
    r_i = e_{i+1} - e_i (i=1..n-1): B(x,r_i) = x_i - x_{i+1} >= 0
    r_n = -e_n:                      B(x,r_n) = x_n >= 0
    r_{n+1} = e0 + e1 + e2 + e3 (n>=3), e0 + e1 + e2 (n=2): B = x0 - x1 - x2 - x3 >= 0."""
    dim = n + 1
    roots = []
    for i in range(1, n):
        r = [0]*dim; r[i+1] = 1; r[i] = -1; roots.append(tuple(r))
    r = [0]*dim; r[n] = -1; roots.append(tuple(r))
    r = [0]*dim; r[0] = 1
    for i in range(1, min(3, n) + 1):
        r[i] = 1
    roots.append(tuple(r))
    return roots

def coxeter_label(r, s):
    """m_ij from the Gram of two roots (both of negative norm)."""
    b = B(r, s); qr, qs = B(r, r), B(s, s)
    c2 = Fraction(b*b, qr*qs)
    return {Fraction(0): 2, Fraction(1, 4): 3, Fraction(1, 2): 4, Fraction(3, 4): 6}.get(c2, 0)  # 0 = infinite

FINITE_ORDERS = {}
def coxeter_order(roots, subset):
    """Order of the parabolic subgroup generated by the reflections in roots[i], i in subset.
    Recognises the finite type of each connected component (A, B, D, E6-8, F4, G2); returns None if infinite."""
    subset = tuple(sorted(subset))
    key = (tuple(roots), subset)
    if key in FINITE_ORDERS:
        return FINITE_ORDERS[key]
    k = len(subset)
    lab = {}
    for a in range(k):
        for b in range(a+1, k):
            m = coxeter_label(roots[subset[a]], roots[subset[b]])
            if m == 0:
                FINITE_ORDERS[key] = None; return None
            if m > 2:
                lab[(a, b)] = m
    # components
    adj = {a: set() for a in range(k)}
    for (a, b) in lab:
        adj[a].add(b); adj[b].add(a)
    seen = set(); order = 1
    for start in range(k):
        if start in seen: continue
        comp = []; stack = [start]
        while stack:
            v = stack.pop()
            if v in seen: continue
            seen.add(v); comp.append(v); stack.extend(adj[v] - seen)
        order *= component_order(comp, adj, lab)
        if order == 0:
            FINITE_ORDERS[key] = None; return None
    FINITE_ORDERS[key] = order
    return order

def component_order(comp, adj, lab):
    kc = len(comp)
    edges = [(a, b) for (a, b) in lab if a in comp]
    if len(edges) != kc - 1:
        return 0                                   # cycle -> affine/infinite
    labels = sorted(lab[e] for e in edges)
    degs = {v: len(adj[v]) for v in comp}
    maxdeg = max(degs.values()) if comp else 0
    big = [m for m in labels if m > 3]
    if kc == 1: return 2
    if not big:
        if maxdeg <= 2: return math.factorial(kc + 1)                     # A_k
        branch = [v for v in comp if degs[v] == 3]
        if len(branch) != 1 or maxdeg > 3: return 0
        v = branch[0]; arms = []
        for w in adj[v]:
            L = 1; prev, cur = v, w
            while degs[cur] == 2:
                nxt = (adj[cur] - {prev}).pop(); prev, cur = cur, nxt; L += 1
            arms.append(L)
        arms.sort()
        if arms[0] == 1 and arms[1] == 1: return 2**(kc-1) * math.factorial(kc)   # D_k
        if arms == [1, 2, 2]: return 51840
        if arms == [1, 2, 3]: return 2903040
        if arms == [1, 2, 4]: return 696729600
        return 0
    if len(big) == 1 and big[0] == 4:
        if maxdeg > 2: return 0
        e4 = [e for e in edges if lab[e] == 4][0]
        ends = [v for v in comp if degs[v] == 1]
        if kc == 2: return 8
        if e4[0] in ends or e4[1] in ends: return 2**kc * math.factorial(kc)         # B_k
        if kc == 4: return 1152                                                        # F_4
        return 0
    if len(big) == 1 and big[0] == 6 and kc == 2: return 12                            # G_2
    return 0

def reflect(x, r):
    q = B(r, r); b = B(x, r)
    t = Fraction(2*b, q)
    assert t.denominator == 1
    t = int(t)
    return tuple(xi - t*ri for xi, ri in zip(x, r))

def bfs_order(roots, subset, cap=2_000_000):
    """Order of the group generated by the reflections in the given roots, by closure on matrices (columns = images of e_i)."""
    dim = len(roots[0])
    basis = [tuple(1 if j == i else 0 for j in range(dim)) for i in range(dim)]
    gens = [tuple(reflect(e, roots[i]) for e in basis) for i in subset]  # matrix as tuple of column images
    def mul(g, h):  # g∘h : columns of h mapped through g
        return tuple(tuple(sum(g[j][k]*h[i][j] for j in range(dim)) for k in range(dim)) for i in range(dim))
    ident = tuple(basis)
    seen = {ident}; frontier = [ident]
    while frontier:
        new = []
        for g in frontier:
            for s in gens:
                h = mul(s, g)
                if h not in seen:
                    seen.add(h); new.append(h)
                    if len(seen) > cap: return None
        frontier = new
    return len(seen)

def chamber_vectors(n, Nmax):
    """All x = (x0,...,xn) in the closed Vinberg chamber with 1 <= Q(x) <= Nmax.  Returns dict N -> list of x."""
    out = {N: [] for N in range(1, Nmax+1)}
    if n >= 3:
        b3 = isqrt(Nmax // (9 - n)) + 1
        b2 = isqrt(3*Nmax // (9 - n)) + 1
    else:
        b3 = 0; b2 = isqrt(Nmax // 2) + 1
    # x2 >= x3 >= ... >= xn >= 0 with x3.. <= b3, x2 <= b2 ; x1 >= x2 ; x0 >= x1+x2+x3 (or x1+x2)
    def tails(prev, depth):
        if depth == 0:
            yield (); return
        for v in range(0, min(prev, b3) + 1):
            for rest in tails(v, depth - 1):
                yield (v,) + rest
    for x2 in range(0, b2 + 1):
        for tail in tails(x2, max(0, n - 2)):
            x3 = tail[0] if n >= 3 else 0
            S_rest = x2*x2 + sum(t*t for t in tail)
            if x2 >= 1:
                x1max = (Nmax + (n-3 if n >= 3 else 0)*x3*x3) // (2*x2) + 1
            else:
                x1max = Nmax // 2 + 1
            for x1 in range(x2, x1max + 1):
                S = S_rest + x1*x1
                lo = max(x1 + x2 + x3, isqrt(S) + 1)
                hi = isqrt(S + Nmax)
                for x0 in range(lo, hi + 1):
                    N = x0*x0 - S
                    if 1 <= N <= Nmax:
                        x = (x0, x1, x2) + tuple(tail)
                        assert all(B(x, r) >= 0 for r in vinberg_roots(n))
                        out[N].append(x)
    return out

def stabilizer_subset(x, roots):
    return [i for i, r in enumerate(roots) if B(x, r) == 0]

def cone_zeta(n, Nmax, check_bfs=False):
    """Returns dict N -> list of (x, |W_x|, primitive?) and r*(N) as Fractions."""
    roots = vinberg_roots(n)
    ch = chamber_vectors(n, Nmax)
    data = {}; rstar = {}; rprim = {}
    for N in range(1, Nmax+1):
        rows = []
        for x in ch[N]:
            sub = stabilizer_subset(x, roots)
            w = coxeter_order(roots, sub)
            assert w is not None, (x, sub)
            if check_bfs:
                wb = bfs_order(roots, sub)
                assert wb == w, (x, sub, w, wb)
            prim = (math.gcd(*x) == 1)
            rows.append((x, w, prim))
        data[N] = rows
        rstar[N] = sum(Fraction(1, w) for _, w, _ in rows)
        rprim[N] = sum(Fraction(1, w) for _, w, p in rows if p)
    return data, rstar, rprim

