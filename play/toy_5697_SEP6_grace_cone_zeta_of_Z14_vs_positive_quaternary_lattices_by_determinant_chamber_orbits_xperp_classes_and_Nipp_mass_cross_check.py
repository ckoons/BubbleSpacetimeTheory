def adjugate(G):
    n = len(G); d = det_int(G)
    Minv = mat_inv_frac(G)
    adj = [[Minv[i][j]*d for j in range(n)] for i in range(n)]
    assert all(a.denominator == 1 for row in adj for a in row)
    return [[int(a) for a in row] for row in adj]

def mat_inv_frac(G):
    n = len(G)
    M = [[Fraction(G[i][j]) for j in range(n)] + [Fraction(1 if i == j else 0) for j in range(n)] for i in range(n)]
    for i in range(n):
        p = next(r for r in range(i, n) if M[r][i] != 0)
        M[i], M[p] = M[p], M[i]
        piv = M[i][i]
        M[i] = [a/piv for a in M[i]]
        for r in range(n):
            if r != i and M[r][i] != 0:
                f = M[r][i]; M[r] = [a - f*b for a, b in zip(M[r], M[i])]
    return [row[n:] for row in M]

def squarefree_factors(N):
    fs = []; m = N; p = 2
    while p*p <= m:
        if m % p == 0:
            fs.append(p); m //= p
            if m % p == 0: return None
        p += 1
    if m > 1: fs.append(m)
    return fs

def disc_constant(G, N):
    """c_L mod N for squarefree N (D(L) = L*/L cyclic of order N): pick an integer vector u with
    w = adj(G) u / N of order N in L*/L (i.e. gcd(N, adj(G) u) = 1); then N*b(w,w) = u^T adj(G) u mod N."""
    adj = adjugate(G); n = len(G)
    for rng in (2, 4, 8):
        for u in itertools.product(range(-rng, rng+1), repeat=n):
            if not any(u): continue
            au = [sum(adj[i][j]*u[j] for j in range(n)) for i in range(n)]
            g = N
            for a in au: g = gcd(g, a)
            if g == 1:
                return sum(u[i]*adj[i][j]*u[j] for i in range(n) for j in range(n)) % N
    return None

def is_square_mod(c, p):
    if p == 2: return True
    return pow(c % p, (p-1)//2, p) == 1 if c % p else True

def admissible(G, N):
    fs = squarefree_factors(N)
    if N == 1: return True
    c = disc_constant(G, N)
    if c is None: return None
    return all(is_square_mod(c, p) for p in fs)

