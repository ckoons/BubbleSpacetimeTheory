def parse_nipp(nipp_dir):
    rows = []
    for fn in sorted(os.listdir(nipp_dir)):
        if not (fn.startswith('nipp_d') and fn.endswith('.html')): continue
        txt = open(os.path.join(nipp_dir, fn), encoding='latin-1').read()
        txt = re.sub(r'<[^>]*>', '', txt)
        for line in txt.splitlines():
            t = line.split()
            if len(t) < 16 or not t[0].isdigit(): continue
            try:
                d, g = int(t[0]), int(t[1]); f = list(map(int, t[2:12]))
                Nlev, Gaut, m1, m2 = int(t[-4]), int(t[-3]), int(t[-2]), int(t[-1])
            except ValueError:
                continue
            f11, f22, f33, f44, f12, f13, f23, f14, f24, f34 = f
            F = [[2*f11, f12, f13, f14], [f12, 2*f22, f23, f24], [f13, f23, 2*f33, f34], [f14, f24, f34, 2*f44]]
            if det_int(F) != d:
                raise ValueError(f'parse: det F != d on line {line!r}')
            rows.append(dict(d=d, g=g, f=f, F=F, level=Nlev, G=Gaut, mass=Fraction(m1, m2), src=fn))
    return rows

def nipp_classes_of_gram_det(rows, N):
    """Classes of positive quaternary lattices with INTEGER Gram matrix and det = N, from Nipp:
    odd lattices at d = 16N with all off-diagonal f even (Gram = F/2); even lattices at d = N (Gram = F)."""
    out = []
    for r in rows:
        if r['d'] == 16*N and all(r['F'][i][j] % 2 == 0 for i in range(4) for j in range(i+1, 4)):
            G = [[r['F'][i][j] // 2 for j in range(4)] for i in range(4)]
            assert det_int(G) == N
            out.append(dict(G=G, aut=r['G'], parity='odd', nipp=r))
        elif r['d'] == N:
            G = [row[:] for row in r['F']]
            assert det_int(G) == N
            out.append(dict(G=G, aut=r['G'], parity='even', nipp=r))
    return out

