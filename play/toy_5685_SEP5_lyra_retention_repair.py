def MI_general(n, dpmf):
    """Exact I(parent;offspring) for ANY switch-pattern distribution dpmf over F_2^n."""
    D = list(itertools.product([0,1],repeat=n)); pri = 1.0/len(D)
    joint = defaultdict(float)
    for d,w in dpmf.items():
        for x in D:
            joint[(x, tuple(a^b for a,b in zip(x,d)))] += pri*w
    py = defaultdict(float)
    for (x,y),p in joint.items(): py[y]+=p
    return sum(p*math.log2(p/(pri*py[y])) for (x,y),p in joint.items() if p>0)

def pmf_independent(n,r):
    return {d: math.prod(r if b else 1-r for b in d) for d in itertools.product([0,1],repeat=n)}
def pmf_exactly_one(n):
    return {tuple(1 if i==j else 0 for i in range(n)): 1.0/n for j in range(n)}
def pmf_hotspot(n, frac):
    """Exactly one crossover, but only in the first ceil(frac*n) junctions."""
    k = max(1,int(round(frac*n)))
    return {tuple(1 if i==j else 0 for i in range(n)): 1.0/k for j in range(k)}
def pmf_correlated(n, seed=3):
    """A deliberately CORRELATED pattern: a random distribution on F_2^n."""
